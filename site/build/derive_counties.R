#!/usr/bin/env Rscript
# Derive geo/wa-counties.js (WA county outlines + label points) from the U.S. Census
# Bureau 2023 cartographic boundary file cb_2023_us_county_500k.zip (public domain;
# acknowledgment required). One-off, developer-time step; the page never runs R.
#
# Usage (from the repository root):
#   Rscript site/build/derive_counties.R <path to cb_2023_us_county_500k.zip>
#
# Needs: R >= 4.4 with sf, jsonlite and openssl already installed. Writes only
# site/geo/wa-counties.js.

suppressPackageStartupMessages({ library(sf); library(jsonlite) })

EXPECTED_SHA256 <- "99d6597b1fc7767deef62e01d28d8b5dcbd578e151855f7dc0d173cbf5bf0868"
SOURCE_URL <- "https://www2.census.gov/geo/tiger/GENZ2023/shp/cb_2023_us_county_500k.zip"

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L || !file.exists(args[1])) {
  stop("Pass the path to cb_2023_us_county_500k.zip (download from ", SOURCE_URL, ")")
}
zip_path <- normalizePath(args[1], winslash = "/")
got <- paste(as.character(openssl::sha256(file(zip_path))), collapse = "")
if (!identical(tolower(got), EXPECTED_SHA256)) {
  stop("SHA-256 mismatch: got ", got, ", expected ", EXPECTED_SHA256)
}

script_dir <- local({
  a <- commandArgs(trailingOnly = FALSE)
  f <- sub("^--file=", "", a[grep("^--file=", a)])
  dirname(normalizePath(f[1]))
})
out_path <- file.path(dirname(script_dir), "geo", "wa-counties.js")

counties <- st_read(paste0("/vsizip/", zip_path), quiet = TRUE)
wa <- counties[counties$STATEFP == "53", c("NAME", "GEOID")]
wa <- st_transform(wa, 4326)
wa <- wa[order(wa$NAME), ]
stopifnot(nrow(wa) == 39L)

# Label anchors: polygon centroids in EPSG:4326 with s2 on (sf default), the same
# st_centroid() call CVI's Maps tab uses for its county label layer.
centroids <- st_coordinates(st_centroid(st_geometry(wa)))

round_coords <- function(g) {
  rapply(unclass(g), function(m) round(m, 5), how = "replace")
}
features <- lapply(seq_len(nrow(wa)), function(i) {
  g <- st_geometry(wa)[[i]]
  type <- if (inherits(g, "MULTIPOLYGON")) "MultiPolygon" else "Polygon"
  list(type = "Feature",
       properties = list(name = wa$NAME[i], fips = wa$GEOID[i]),
       geometry = list(type = type, coordinates = round_coords(g)))
})
labels <- lapply(seq_len(nrow(wa)), function(i)
  list(name = wa$NAME[i], lon = round(centroids[i, 1], 5), lat = round(centroids[i, 2], 5)))

payload <- list(
  source = paste0("U.S. Census Bureau, 2023 cartographic boundary file cb_2023_us_county_500k ",
                  "(STATEFP 53), SHA-256 ", EXPECTED_SHA256, "; transformed to EPSG:4326, ",
                  "coordinates rounded to 5 decimals"),
  attribution = "Boundaries: U.S. Census Bureau",
  counties = list(type = "FeatureCollection", features = features),
  labels = labels)

json <- toJSON(payload, auto_unbox = TRUE, digits = NA)
writeLines(c(
  "/* Generated by build/derive_counties.R from public-domain U.S. Census Bureau boundaries. Do not edit. */",
  paste0("window.CVIWA_GEO = ", json, ";")), out_path, useBytes = TRUE)
cat("wrote", out_path, "\n")
